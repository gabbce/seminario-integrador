import { test, expect } from '@playwright/test'
async function login(page: import('@playwright/test').Page, role = 'bedel') {
  await page.goto('/')
  await page.getByLabel('Correo electrónico').fill(`${role}@demo.local`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Aulas2026')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
}
test('reserva periódica completa y lectura desde agenda', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await login(page)
  await page.screenshot({ path: 'evidence/agenda-desktop.png' })
  await page.getByRole('button', { name: 'Nueva reserva' }).click()
  await page.screenshot({ path: 'evidence/reserva-desktop.png', fullPage: true, animations: "disabled" })
  await page.getByRole('button', { name: 'Buscar aulas' }).click()
  const monday = page.getByRole('group', { name: /Lunes/ })
  await expect(monday.getByText('Aula 105', { exact: true })).toHaveCount(0)
  await monday.getByRole('radio').first().check()
  await page.getByRole('group', { name: /Miércoles/ }).getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Volver', exact: true }).click()
  await page.getByRole('button', { name: 'Buscar aulas' }).click()
  await expect(monday.getByRole('radio').first()).toBeChecked()
  await page.getByRole('button', { name: 'Revisar reserva' }).click()
  await page.getByRole('button', { name: 'Volver', exact: true }).click()
  await expect(monday.getByRole('radio').first()).toBeChecked()
  await page.getByRole('button', { name: 'Revisar reserva' }).click()
  await page.getByRole('button', { name: 'Confirmar reserva' }).click()
  await expect(page.getByRole('heading', { name: 'Reserva confirmada' })).toBeVisible()
  await page.getByRole('button', { name: 'Ver detalle' }).click()
  await expect(page.getByRole('heading', { name: '26 clases registradas' })).toBeVisible()
  await page.getByRole('link', { name: 'Agenda', exact: true }).click()
  await expect(page.getByRole('button', { name: /Matemática I/ }).first()).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'evidence/agenda-mobile.png', fullPage: true, animations: "disabled" })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
